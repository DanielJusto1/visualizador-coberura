"""Web interface for radiocoverage (Streamlit).

Run locally with:

    streamlit run app/streamlit_app.py
"""

import sys
import tempfile
from dataclasses import replace
from pathlib import Path

import streamlit as st
import streamlit.components.v1 as components

# Make the package importable when the app runs from a fresh clone (e.g. Streamlit Cloud).
sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

from radiocoverage.bands import BANDS  # noqa: E402
from radiocoverage.coverage import Receiver, Site, compute_coverage  # noqa: E402
from radiocoverage.coverage_map import build_coverage_map  # noqa: E402
from radiocoverage.geo import GeoPoint, is_in_spain  # noqa: E402
from radiocoverage.kmz import save_kmz  # noqa: E402
from radiocoverage.link_budget import LinkParameters, compute_link_budget  # noqa: E402
from radiocoverage.link_map import build_link_map  # noqa: E402
from radiocoverage.path import LinkPath  # noqa: E402
from radiocoverage.profile import plot_profile, terrain_profile  # noqa: E402
from radiocoverage.propagation import ENVIRONMENTS, MODEL_CHOICES  # noqa: E402
from radiocoverage.receiver import sensitivity_dbm  # noqa: E402
from radiocoverage.terrain import TerrariumTiles  # noqa: E402

PLACES = {
    "Madrid - Puerta del Sol": (40.4169, -3.7035),
    "Madrid - Torrespaña": (40.4233, -3.6714),
    "Barcelona - Plaça de Catalunya": (41.3870, 2.1701),
    "Valencia - Plaza del Ayuntamiento": (39.4699, -0.3763),
    "Sevilla - Catedral": (37.3858, -5.9931),
    "Bilbao - Guggenheim": (43.2687, -2.9340),
    "Segovia - Plaza Mayor": (40.9481, -4.1253),
    "Sierra de Guadarrama - Bola del Mundo": (40.7930, -3.9620),
    "Granada - Alhambra": (37.1761, -3.5881),
    "Tenerife - Santa Cruz": (28.4636, -16.2518),
}
BAND_NAMES = [band.name for band in BANDS.values()]

st.set_page_config(page_title="Radio coverage · LTE/5G Spain", page_icon="📡", layout="wide")


@st.cache_resource
def terrain_source() -> TerrariumTiles:
    return TerrariumTiles()


def location_input(label: str, default: str, key: str) -> GeoPoint:
    place = st.selectbox(label, list(PLACES), index=list(PLACES).index(default), key=f"{key}_p")
    lat0, lon0 = PLACES[place]
    col1, col2 = st.columns(2)
    lat = col1.number_input("Latitude", value=lat0, format="%.5f", key=f"{key}_lat_{place}")
    lon = col2.number_input("Longitude", value=lon0, format="%.5f", key=f"{key}_lon_{place}")
    return GeoPoint(lat, lon)


def radio_inputs(key: str, default_band: str) -> dict:
    band = BANDS[
        st.selectbox(
            "Band", BAND_NAMES, index=BAND_NAMES.index(default_band), key=f"{key}_band"
        ).lower()
    ]
    st.caption(f"{band.technology} · {band.centre_mhz:g} MHz · {band.typical_use}")
    col1, col2, col3 = st.columns(3)
    return {
        "band": band,
        "tx_power": col1.number_input("Tx power (dBm)", value=46.0, step=1.0, key=f"{key}_pw"),
        "tx_gain": col2.number_input("Antenna gain (dBi)", value=17.0, step=1.0, key=f"{key}_g"),
        "tx_height": col3.number_input(
            "Mast height (m)", value=30.0, min_value=1.0, key=f"{key}_h"
        ),  # fmt: skip
    }


def receiver_inputs(key: str) -> dict:
    col1, col2, col3 = st.columns(3)
    bandwidth = col1.number_input("Channel (MHz)", value=10.0, min_value=0.1, key=f"{key}_bw")
    noise_figure = col2.number_input("Noise figure (dB)", value=9.0, key=f"{key}_nf")
    snr = col3.number_input("Min. SNR (dB)", value=-1.0, key=f"{key}_snr")
    col4, col5, col6 = st.columns(3)
    return {
        "sensitivity": sensitivity_dbm(bandwidth, noise_figure, snr),
        "margin": col4.number_input("Fade margin (dB)", value=5.0, min_value=0.0, key=f"{key}_m"),
        "rx_loss": col5.number_input("Body loss (dB)", value=3.0, min_value=0.0, key=f"{key}_bl"),
        "other": col6.number_input("Other losses (dB)", value=0.0, min_value=0.0, key=f"{key}_o"),
    }


def propagation_inputs(key: str, default_environment: str = "urban") -> dict:
    col1, col2, col3 = st.columns(3)
    return {
        "model": col1.selectbox("Model", MODEL_CHOICES, key=f"{key}_model"),
        "environment": col2.selectbox(
            "Environment", ENVIRONMENTS, index=ENVIRONMENTS.index(default_environment),
            key=f"{key}_env",
        ),  # fmt: skip
        "terrain": col3.toggle("Real terrain", value=False, key=f"{key}_terrain",
                               help="Downloads elevation data the first time (a few seconds)"),
    }  # fmt: skip


def show_map(m, height: int = 620) -> None:
    html = m.get_root().render()  # generated by this app, not user-supplied HTML
    if hasattr(st, "iframe"):
        st.iframe(html, height=height)
    else:  # older Streamlit versions
        components.html(html, height=height)


st.title("📡 Radio coverage visualizer · LTE/5G in Spain")
st.write(
    "Link budget and coverage prediction with Okumura-Hata, COST-231 and 3GPP TR 38.901 "
    "models, real terrain (Bullington diffraction, ITU-R P.526) and Spanish LTE/5G bands."
)

coverage_tab, link_tab = st.tabs(["Coverage map", "Point-to-point link"])

with coverage_tab:
    left, right = st.columns([1, 2])
    with left:
        st.subheader("Base station")
        location = location_input("Site", "Madrid - Puerta del Sol", "cov")
        radio = radio_inputs("cov", "B20")
        sector = st.toggle("Sector antenna", value=True, key="cov_sector")
        azimuth = st.slider("Azimuth (°)", 0, 359, 0, key="cov_az") if sector else None
        st.subheader("Receiver")
        receiver_values = receiver_inputs("cov")
        st.subheader("Propagation and area")
        propagation = propagation_inputs("cov")
        col1, col2 = st.columns(2)
        radius = col1.slider("Radius (km)", 1.0, 30.0, 5.0, 0.5, key="cov_r")
        resolution = col2.select_slider("Resolution (m)", [25, 50, 100, 200, 400], 100,
                                        key="cov_res")  # fmt: skip
        run_coverage = st.button("Compute coverage", type="primary", key="cov_run")

    with right:
        if run_coverage:
            try:
                if not is_in_spain(location):
                    raise ValueError("The site must be in Spain")
                site = Site(
                    "Site", location, radio["band"].centre_mhz, radio["tx_power"],
                    radio["tx_gain"], height_m=radio["tx_height"], azimuth_deg=azimuth,
                    band_name=f"{radio['band'].technology} {radio['band'].name}",
                )  # fmt: skip
                receiver = Receiver(
                    receiver_values["sensitivity"],
                    loss_db=receiver_values["rx_loss"],
                    other_losses_db=receiver_values["other"],
                    required_margin_db=receiver_values["margin"],
                )
                with st.spinner("Computing coverage..."):
                    result = compute_coverage(
                        [site], receiver, radius, resolution, propagation["model"],
                        propagation["environment"],
                        terrain_source() if propagation["terrain"] else None,
                    )  # fmt: skip
                st.session_state["coverage"] = result
            except (ValueError, OSError) as exc:
                st.error(str(exc))
        result = st.session_state.get("coverage")
        if result is None:
            st.info("Choose the parameters and press **Compute coverage**.")
        else:
            col1, col2, col3 = st.columns(3)
            col1.metric("Covered area", f"{result.covered_area_km2:.1f} km²")
            col2.metric("Covered fraction", f"{result.covered_fraction:.0%}")
            col3.metric("Sensitivity", f"{result.receiver.sensitivity_dbm:.1f} dBm")
            show_map(build_coverage_map(result))
            with tempfile.TemporaryDirectory() as tmp:
                kmz = save_kmz(result, Path(tmp) / "coverage.kmz").read_bytes()
            st.download_button("Download KMZ (Google Earth)", kmz, "coverage.kmz",
                               "application/vnd.google-earth.kmz")  # fmt: skip

with link_tab:
    left, right = st.columns([1, 2])
    with left:
        st.subheader("Transmitter")
        tx = location_input("Transmitter", "Sierra de Guadarrama - Bola del Mundo", "tx")
        radio_l = radio_inputs("link", "B20")
        st.subheader("Receiver")
        rx = location_input("Receiver", "Segovia - Plaza Mayor", "rx")
        rx_height = st.number_input("Receiver height (m)", value=1.5, min_value=0.1, key="rx_h")
        receiver_l = receiver_inputs("link")
        st.subheader("Propagation")
        propagation_l = propagation_inputs("link", default_environment="rural")
        run_link = st.button("Compute link", type="primary", key="link_run")

    with right:
        if run_link:
            try:
                for point in (tx, rx):
                    if not is_in_spain(point):
                        raise ValueError(f"{point} is outside Spain")
                band = radio_l["band"]
                path = LinkPath(tx, rx, band.centre_mhz)
                params = LinkParameters(
                    frequency_mhz=band.centre_mhz,
                    distance_km=path.distance_km,
                    tx_power_dbm=radio_l["tx_power"],
                    rx_sensitivity_dbm=receiver_l["sensitivity"],
                    tx_antenna_gain_dbi=radio_l["tx_gain"],
                    rx_cable_loss_db=receiver_l["rx_loss"],
                    other_losses_db=receiver_l["other"],
                    required_margin_db=receiver_l["margin"],
                    model=propagation_l["model"],
                    environment=propagation_l["environment"],
                    tx_height_m=radio_l["tx_height"],
                    rx_height_m=rx_height,
                )
                profile, png = None, None
                if propagation_l["terrain"]:
                    with st.spinner("Reading terrain..."):
                        profile = terrain_profile(path, terrain_source(), radio_l["tx_height"],
                                                  rx_height)  # fmt: skip
                    params = replace(params, terrain_loss_db=profile.diffraction_loss_db)
                    with tempfile.TemporaryDirectory() as tmp:
                        png = plot_profile(profile, Path(tmp) / "p.png").read_bytes()
                st.session_state["link"] = (path, compute_link_budget(params), band, profile, png)
            except (ValueError, OSError) as exc:
                st.error(str(exc))
        stored = st.session_state.get("link")
        if stored is None:
            st.info("Choose both ends of the link and press **Compute link**.")
        else:
            path, budget, band, profile, png = stored
            if budget.is_viable:
                st.success(f"LINK OK · margin {budget.margin_db:.1f} dB")
            else:
                st.error(f"LINK FAILS · margin {budget.margin_db:.1f} dB")
            col1, col2, col3, col4 = st.columns(4)
            col1.metric("Distance", f"{path.distance_km:.2f} km")
            col2.metric("Path loss", f"{budget.path_loss_db:.1f} dB")
            col3.metric("Received power", f"{budget.rx_power_dbm:.1f} dBm")
            col4.metric("Azimuth", f"{path.bearing_deg:.1f}°")
            for warning in budget.warnings:
                st.warning(warning)
            if png is not None:
                st.image(png, caption=f"Terrain: {profile.status}")
            show_map(build_link_map(path, budget, band, profile), height=520)
